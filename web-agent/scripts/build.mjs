import { readFile, writeFile, mkdir, rm } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = p => readFile(resolve(root, p), 'utf8');
const [html, css, js, tools, model, worker, manifest] = await Promise.all([
  read('web/index.html'), read('web/style.css'), read('web/app.js'),
  read('src/tools.mjs'), read('src/model.mjs'), read('src/worker.mjs'), read('.openai/hosting.json'),
]);
JSON.parse(manifest);
// Each source module has a private closure; the deployed Worker has no external imports.
function wrap(source, exports) {
  const cleaned = source.replace(/^export\s+(?=(?:async\s+)?(?:function|const|let|class)\b)/gm, '');
  if (/^import\s|^export\s/m.test(cleaned)) throw new Error('Unexpected module declaration in a bundled module.');
  return `(()=>{\n${cleaned}\nreturn {${exports.join(',')}};\n})()`;
}
const ui = `const UI_HTML=${JSON.stringify(html)};\nconst UI_CSS=${JSON.stringify(css)};\nconst UI_JS=${JSON.stringify(js)};\n`;
const entry = worker.replace(/^import .*;\r?\n/gm, '');
const bundled = `// SOLRDM web: dependency-free Worker bundle. Generated by scripts/build.mjs.\n${ui}\nconst {executeTool,TOOL_DEFINITIONS}=${wrap(tools,['executeTool','TOOL_DEFINITIONS'])};\nconst {runAgent}=${wrap(model,['runAgent'])};\n${entry}`;
await mkdir(resolve(root, 'worker'), { recursive: true });
await writeFile(resolve(root, 'worker/index.js'), bundled);
await rm(resolve(root, 'dist'), { recursive: true, force: true });
await mkdir(resolve(root, 'dist/server'), { recursive: true });
await mkdir(resolve(root, 'dist/.openai'), { recursive: true });
await writeFile(resolve(root, 'dist/server/index.js'), bundled);
await writeFile(resolve(root, 'dist/.openai/hosting.json'), manifest);
await writeFile(resolve(root, 'src/ui.mjs'), `export ${ui.replace(/\nconst UI_/g, '\nexport const UI_')}`);
console.log(`Built dependency-free Worker (${Buffer.byteLength(bundled)} bytes).`);
